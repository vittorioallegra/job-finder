/** US states and the District of Columbia: "Los Angeles, CA" is the United States. */
const US_STATES = new Set(
  "AL AK AZ AR CA CO CT DE FL GA HI ID IL IN IA KS KY LA ME MD MA MI MN MS MO MT NE NV NH NJ NM NY NC ND OH OK OR PA RI SC SD TN TX UT VT VA WA WV WI WY DC".split(
    " ",
  ),
);

let index: Map<string, string> | undefined;

function cityIndex(): Map<string, string> {
  if (index) return index;
  index = new Map();
  for (const [code, cities] of Object.entries(CITIES)) {
    for (const city of cities) index.set(foldForMatch(city), code);
  }
  return index;
}

