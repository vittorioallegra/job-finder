/** The main city of a country, for a search that names it; undefined when the list has none. */
export function mainCity(code: string): string | undefined {
  return MAIN_CITY[code];
}

/** The country of a well-known city, or undefined. */
export function countryOfCity(city: string): string | undefined {
  const folded = foldForMatch(city);
  return folded === "" ? undefined : cityIndex().get(folded);
}

/** True for a two-letter US state code written as such ("CA", "NY"). */
export function isUsStateCode(part: string): boolean {
  return /^[A-Z]{2}$/.test(part.trim()) && US_STATES.has(part.trim());
}
